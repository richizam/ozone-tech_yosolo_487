# ----------------------------------------------------------- style helpers
def base_styles(doc):
    st = doc.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(14)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    pf = st.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf.first_line_indent = Cm(1.25)
    pf.space_before = Pt(0)
    pf.space_after = Pt(0)
    for name, sz in (("Heading 1", 16), ("Heading 2", 14), ("Heading 3", 14)):
        h = doc.styles[name]
        h.font.name = "Times New Roman"
        h.font.size = Pt(sz)
        h.font.bold = True
        h.font.color.rgb = None            # черный, не «вордовский» синий
        rf = h.element.rPr.rFonts
        # тема Word (asciiTheme=majorHAnsi) перекрывает font.name — задаем
        # гарнитуру явно и снимаем тематические атрибуты
        for attr in ("w:asciiTheme", "w:hAnsiTheme", "w:cstheme",
                     "w:eastAsiaTheme"):
            if rf.get(qn(attr)) is not None:
                del rf.attrib[qn(attr)]
        for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
            rf.set(qn(attr), "Times New Roman")
        hp = h.paragraph_format
        hp.alignment = WD_ALIGN_PARAGRAPH.LEFT   # заголовки не выключают
        hp.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
        hp.space_before = Pt(12)
        hp.space_after = Pt(6)
        hp.first_line_indent = Cm(1.25)
        hp.keep_with_next = True


def set_margins(section):
    section.page_width = Mm(210)
    section.page_height = Mm(297)
    section.left_margin = Mm(30)
    section.right_margin = Mm(15)
    section.top_margin = Mm(20)
    section.bottom_margin = Mm(20)


def footer_page_number(section):
    p = section.footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    for tag, attrs, text in (("w:fldChar", {"w:fldCharType": "begin"}, None),
                             ("w:instrText", {"xml:space": "preserve"}, "PAGE"),
                             ("w:fldChar", {"w:fldCharType": "end"}, None)):
        el = OxmlElement(tag)
        for k, v in attrs.items():
            el.set(qn(k), v)
        if text:
            el.text = text
        run._r.append(el)
    run.font.name = "Times New Roman"
    run.font.size = Pt(12)


def auto_update_fields(doc):
    el = OxmlElement("w:updateFields")
    el.set(qn("w:val"), "true")
    doc.settings.element.append(el)


def toc_field(doc):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(0)
    run = p.add_run()
    fld = OxmlElement("w:fldChar")
    fld.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = ' TOC \\o "1-2" \\h \\z \\u '
    sep = OxmlElement("w:fldChar")
    sep.set(qn("w:fldCharType"), "separate")
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    for el in (fld, instr, sep, end):
        run._r.append(el)


def par(doc, text, indent=True, align=None, bold=False, size=None,
        space_after=0):
    p = doc.add_paragraph()
    if not indent:
        p.paragraph_format.first_line_indent = Cm(0)
    if align is not None:
        p.alignment = align
    if space_after:
        p.paragraph_format.space_after = Pt(space_after)
    r = p.add_run(text)
    r.bold = bold
    if size:
        r.font.size = Pt(size)
    return p


def listing(doc, items):
    """Перечисление по ГОСТ: тире, со строчной буквы, «;» между элементами."""
    for i, it in enumerate(items):
        tail = ";" if i < len(items) - 1 else "."
        p = doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(1.25)
        p.add_run("– " + it + tail)


TBL_N = {"n": 0}
FIG_N = {"n": 0}


def table(doc, caption, headers, rows, widths=None):
    TBL_N["n"] += 1
    cap = doc.add_paragraph()
    cap.paragraph_format.first_line_indent = Cm(0)
    cap.paragraph_format.keep_with_next = True
    cap.add_run(f"Таблица {TBL_N['n']} — {caption}")
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(headers):
        c = t.rows[0].cells[j]
        c.text = ""
        p = c.paragraphs[0]
        p.paragraph_format.first_line_indent = Cm(0)
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(h)
        r.bold = True
        r.font.size = Pt(12)
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            c = t.rows[1 + i].cells[j]
            c.text = ""
            p = c.paragraphs[0]
            p.paragraph_format.first_line_indent = Cm(0)
            p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
            r = p.add_run(str(val))
            r.font.size = Pt(12)
    if widths:
        for j, w in enumerate(widths):
            for row in t.rows:
                row.cells[j].width = Cm(w)
    par(doc, "", indent=False)
    return t


def figure(doc, path, caption, width_cm=16.0):
    if not Path(path).is_file():
        return
    FIG_N["n"] += 1
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    p.add_run().add_picture(str(path), width=Cm(width_cm))
    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.first_line_indent = Cm(0)
    cap.paragraph_format.space_after = Pt(12)
    r = cap.add_run(f"Рисунок {FIG_N['n']} — {caption}")
    r.font.size = Pt(12)


